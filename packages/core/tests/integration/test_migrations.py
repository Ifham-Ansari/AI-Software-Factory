"""Migrations apply cleanly and revert cleanly.

A migration that cannot be undone cannot be safely deployed, so ``downgrade`` is tested as
seriously as ``upgrade``. The schema built by migrations is also compared against the
schema built from the ORM models: when those two drift, autogenerate starts producing
migrations that try to "fix" a difference that only exists on one side.
"""

from __future__ import annotations

import asyncio
from collections.abc import AsyncIterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import inspect
from sqlalchemy.ext.asyncio import AsyncEngine

from factory_core.config import DatabaseSettings
from factory_core.persistence import Base, create_engine

pytestmark = pytest.mark.integration

EXPECTED_TABLES = {"users", "refresh_tokens", "projects", "audit_log", "email_verifications"}


def _alembic_config(database_url: str) -> Config:
    """Build an Alembic config pointed at the test database."""
    root = Path(__file__).resolve().parents[4]
    config = Config(str(root / "alembic.ini"))
    config.set_main_option(
        "script_location", str(root / "packages/core/src/factory_core/migrations")
    )
    # Passed through the config, not the environment: env.py deliberately ignores
    # TEST_DATABASE_URL so a developer's .env cannot redirect a real migration.
    config.set_main_option("sqlalchemy.url", database_url)
    return config


async def _alembic(action: str, database_url: str, revision: str) -> None:
    """Run an Alembic command off the event loop.

    Alembic's API is synchronous and our ``env.py`` drives an async engine with
    ``asyncio.run()``. Calling it directly from an async test would mean starting a loop
    inside a running one, which fails with "coroutine was never awaited" — so it runs in a
    worker thread that has no loop of its own.
    """
    config = _alembic_config(database_url)
    runner = command.upgrade if action == "upgrade" else command.downgrade
    await asyncio.to_thread(runner, config, revision)


@pytest.fixture
async def clean_engine(database_url: str, rebuild_schema_after: None) -> AsyncIterator[AsyncEngine]:
    """An engine over a database with no schema at all.

    Deliberately does not use the shared session engine: these tests create and destroy
    the schema themselves, which would leave every other test's fixture looking at tables
    that no longer exist.
    """
    settings = DatabaseSettings(url=database_url)  # type: ignore[arg-type]
    engine = create_engine(settings, application_name="factory-migration-tests")
    async with engine.begin() as connection:
        await connection.run_sync(Base.metadata.drop_all)
        await connection.exec_driver_sql("DROP TABLE IF EXISTS alembic_version")

    yield engine

    # Leave the database clean and tell the shared fixture to rebuild, so these tests
    # can run in any position without breaking the ones around them.
    async with engine.begin() as connection:
        await connection.run_sync(Base.metadata.drop_all)
        await connection.exec_driver_sql("DROP TABLE IF EXISTS alembic_version")
    await engine.dispose()


async def _table_names(engine: AsyncEngine) -> set[str]:
    async with engine.connect() as connection:
        return set(await connection.run_sync(lambda sync: inspect(sync).get_table_names()))


class TestMigrations:
    async def test_upgrade_creates_every_table(
        self, clean_engine: AsyncEngine, database_url: str
    ) -> None:
        await _alembic("upgrade", database_url, "head")

        assert EXPECTED_TABLES.issubset(await _table_names(clean_engine))

    async def test_downgrade_removes_every_table(
        self, clean_engine: AsyncEngine, database_url: str
    ) -> None:
        await _alembic("upgrade", database_url, "head")

        await _alembic("downgrade", database_url, "base")

        assert not EXPECTED_TABLES & await _table_names(clean_engine)

    async def test_upgrade_downgrade_upgrade(
        self, clean_engine: AsyncEngine, database_url: str
    ) -> None:
        """A migration that only works once is not reversible."""
        await _alembic("upgrade", database_url, "head")
        await _alembic("downgrade", database_url, "base")
        await _alembic("upgrade", database_url, "head")

        assert EXPECTED_TABLES.issubset(await _table_names(clean_engine))

    async def test_migrated_schema_matches_the_models(
        self, clean_engine: AsyncEngine, database_url: str
    ) -> None:
        """Drift here makes every future autogenerated migration wrong."""
        await _alembic("upgrade", database_url, "head")

        async with clean_engine.connect() as connection:
            migrated = await connection.run_sync(
                lambda sync: {
                    table: {column["name"] for column in inspect(sync).get_columns(table)}
                    for table in EXPECTED_TABLES
                }
            )

        for table_name in EXPECTED_TABLES:
            expected = {column.name for column in Base.metadata.tables[table_name].columns}
            assert migrated[table_name] == expected, f"{table_name} drifted from the model"

    async def test_0002_backfills_existing_users_as_verified(
        self, clean_engine: AsyncEngine, database_url: str
    ) -> None:
        """Accounts created before verification existed must not be locked out.

        They had no way to satisfy a rule that did not exist yet, so 0002 grandfathers
        them in rather than leaving every current user unable to sign in.
        """
        from sqlalchemy import text

        await _alembic("upgrade", database_url, "0001")

        async with clean_engine.begin() as connection:
            await connection.execute(
                text(
                    "INSERT INTO users (id, email, display_name, password_hash, status, "
                    "created_at, updated_at) VALUES "
                    "(gen_random_uuid(), 'pre-existing@example.com', 'Pre Existing', "
                    "'$argon2id$fake', 'active', now(), now())"
                )
            )

        await _alembic("upgrade", database_url, "head")

        async with clean_engine.connect() as connection:
            result = await connection.execute(
                text(
                    "SELECT email_verified_at FROM users WHERE email = 'pre-existing@example.com'"
                )
            )
            verified_at = result.scalar_one()
        assert verified_at is not None

    async def test_constraint_names_match_the_convention(
        self, clean_engine: AsyncEngine, database_url: str
    ) -> None:
        """Unnamed constraints make autogenerate unable to alter them later."""
        await _alembic("upgrade", database_url, "head")

        async with clean_engine.connect() as connection:
            checks = await connection.run_sync(
                lambda sync: inspect(sync).get_check_constraints("users")
            )
            unique = await connection.run_sync(
                lambda sync: inspect(sync).get_unique_constraints("users")
            )

        assert any(c["name"] == "ck_users_status_valid" for c in checks)
        assert any(u["name"] == "uq_users_email" for u in unique)
